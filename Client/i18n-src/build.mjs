// Builds assets/i18n/<code>.js (one file per language, loaded by assets/i18n.js) from the phrase files in
// this folder. Run it after changing any of them:   node i18n-src/build.mjs
//
// Each phrase file exports rows of  'English': [zh, hi, es, ar, fr, bn, pt, ru, ur, yue, id].
// Placeholders (see assets/i18n.js): %1 %2 numbers, {0} {1} tags inside a sentence, $1 $2 filled-in words.
// Every translation has to keep the same placeholders as its English, or the build stops and says where.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const LANGS = ['zh', 'hi', 'es', 'ar', 'fr', 'bn', 'pt', 'ru', 'ur', 'yue', 'id'];
const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(here, '..', 'public', 'assets', 'i18n');

const files = fs.readdirSync(here).filter((f) => f.endsWith('.mjs') && f !== 'build.mjs').sort();
const all = {}, problems = [];
const marks = (s) => (s.match(/%\d|\{\d+\}|\$\d/g) || []).sort().join(' ');
// Letters from another language's script slipping in (a Devanagari letter in Bengali, Cyrillic in Spanish…)
const SCRIPT = { han: /\p{Script=Han}/u, deva: /\p{Script=Devanagari}/u, beng: /\p{Script=Bengali}/u, arab: /\p{Script=Arabic}/u, cyr: /\p{Script=Cyrillic}/u };
const OWN = { zh: 'han', hi: 'deva', ar: 'arab', bn: 'beng', ru: 'cyr', ur: 'arab', yue: 'han' };
const foreign = (code, t) => Object.entries(SCRIPT).filter(([name, re]) => name !== OWN[code] && re.test(t)).map(([name]) => name);
for (const f of files) {
  const rows = (await import(pathToFileURL(path.join(here, f)).href)).default;
  for (const [en, tr] of Object.entries(rows)) {
    if (all[en]) problems.push(`${f}: "${en}" is also in another file`);
    if (!Array.isArray(tr) || tr.length !== LANGS.length) { problems.push(`${f}: "${en}" has ${tr?.length} translations, needs ${LANGS.length}`); continue; }
    tr.forEach((t, i) => {
      if (typeof t !== 'string' || !t.trim()) problems.push(`${f}: "${en}" is empty in ${LANGS[i]}`);
      else if (marks(t) !== marks(en)) problems.push(`${f}: "${en}" in ${LANGS[i]} has placeholders [${marks(t)}], English has [${marks(en)}]`);
      else if (foreign(LANGS[i], t).length) problems.push(`${f}: "${en}" in ${LANGS[i]} has ${foreign(LANGS[i], t)} letters: ${t}`);
    });
    all[en] = tr;
  }
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

fs.mkdirSync(outDir, { recursive: true });
LANGS.forEach((code, i) => {
  const map = Object.fromEntries(Object.entries(all).map(([en, tr]) => [en, tr[i]]));
  fs.writeFileSync(path.join(outDir, code + '.js'),
    `/* Generated by i18n-src/build.mjs from the phrase files in i18n-src/. Edit those, then run the build. */\n` +
    `Momento.i18n.add(${JSON.stringify(map, null, 0).replace(/","/g, '",\n"')});\n`);
});
console.log(`${Object.keys(all).length} phrases × ${LANGS.length} languages from ${files.join(', ')}`);
